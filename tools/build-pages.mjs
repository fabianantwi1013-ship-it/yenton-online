// Builds the parts of the site that link previews and Google need as plain HTML:
//   - one page per product (product-<id>.html), so each product has its own shareable link
//   - 404.html, which also shows products added to the sheet since the last build
//   - WhatsApp/Facebook link preview tags on every page
//   - sitemap.xml and robots.txt
// Products come from the Google Sheet when CONFIG.productsSheet is set, otherwise from data.js.
// Run it after changing products:   node tools/build-pages.mjs
// (The "Update product pages" GitHub Action also runs it every hour.)
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(root, f), "utf8");
const write = (f, s) => fs.writeFileSync(path.join(root, f), s);

const ctx = { console };
vm.runInNewContext(read("data.js") + "\n" + read("sheet.js") + "\n;this.d = { CONFIG, CATEGORIES, REGIONS, PRODUCTS, Sheet };", ctx);
const { CONFIG, CATEGORIES, REGIONS, Sheet } = ctx.d;
let PRODUCTS = ctx.d.PRODUCTS;

if (CONFIG.productsSheet) {
  const res = await fetch(CONFIG.productsSheet);
  if (!res.ok) throw new Error(`Couldn't read the Google Sheet (HTTP ${res.status}). Is it published to the web?`);
  const fromSheet = Sheet.toProducts(await res.text(), CATEGORIES, REGIONS, CONFIG.whatsapp);
  if (!fromSheet.length) throw new Error("The Google Sheet has no usable products, so nothing was changed.");
  PRODUCTS = fromSheet;
  console.log(`Read ${PRODUCTS.length} products from the Google Sheet.`);
}

const base = `https://${CONFIG.siteUrl}/`;
const escape = (s) =>
  String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const cedi = (n) => "GH₵ " + n.toLocaleString("en-GH");
const catById = Object.fromEntries(CATEGORIES.map((c) => [c.id, c]));

// WhatsApp doesn't preview .webp on every phone, so previews use a .jpg copy from assets/photos/og/ when there is one.
function previewImage(src) {
  if (!src) return base + "assets/og-image.jpg";
  if (src.startsWith(base)) src = src.slice(base.length);
  if (/^https?:/.test(src)) return src;
  const jpg = `assets/photos/og/${path.basename(src).replace(/\.\w+$/, ".jpg")}`;
  return base + (fs.existsSync(path.join(root, jpg)) ? jpg : src);
}

function previewTags({ title, description, url, image, type = "website" }) {
  return `<!-- link-preview: generated by tools/build-pages.mjs -->
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="${type}">
  <meta property="og:site_name" content="Yɛntɔn Online">
  <meta property="og:title" content="${escape(title)}">
  <meta property="og:description" content="${escape(description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${image}">
  <meta property="og:locale" content="en_GH">
  <meta name="twitter:card" content="summary_large_image">
  <!-- /link-preview -->`;
}

// ---------- preview tags on the hand-written pages ----------
const generated = (f) => /^product-\d+\.html$/.test(f) || f === "404.html";
const pages = fs.readdirSync(root).filter((f) => f.endsWith(".html") && !generated(f));
for (const file of pages) {
  let html = read(file);
  const title = (html.match(/<title>(.*?)<\/title>/) || [])[1] || "Yɛntɔn Online";
  const description = (html.match(/<meta name="description" content="(.*?)">/) || [])[1] || "";
  const tags = previewTags({
    title: title.replace(/&amp;/g, "&"), description: description.replace(/&amp;/g, "&"),
    url: base + (file === "index.html" ? "" : file),
    image: base + "assets/og-image.jpg",
  });
  html = html.includes("<!-- link-preview")
    ? html.replace(/<!-- link-preview[\s\S]*?<!-- \/link-preview -->/, tags)
    : html.replace(/(<meta name="description"[^>]*>)/, `$1\n  ${tags}`);
  write(file, html);
}

// ---------- product pages ----------
function productPage({ head, product = "", crumbs, view, moreTitle, moreLink }) {
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  ${head}
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Lilita+One&family=Plus+Jakarta+Sans:wght@400;500;600;700;800&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="styles.css">
  <link rel="manifest" href="manifest.json">
  <meta name="theme-color" content="#0a7a36">
  <link rel="icon" href="assets/icon-192.png">
  <link rel="apple-touch-icon" href="assets/apple-touch-icon.png">
</head>
<body data-page="shop" data-product="${product}">
<div id="site-header"></div>

<main>
  <section class="page-hero page-hero-slim">
    <div class="container">
      <p class="crumbs">${crumbs}</p>
    </div>
  </section>

  <section class="section section-tight">
    <div class="container" id="productView">
      ${view}
    </div>
  </section>

  <section class="section section-tight">
    <div class="container" id="safetyTips"></div>
  </section>

  <section class="section section-alt">
    <div class="container">
      <div class="section-head">
        <div>
          <p class="eyebrow">More like this</p>
          <h2>${moreTitle}</h2>
        </div>
        <a class="btn btn-outline btn-sm" href="${moreLink}">See all →</a>
      </div>
      <div class="product-grid" id="relatedGrid"></div>
    </div>
  </section>
</main>

<div id="site-footer"></div>
<script src="i18n.js"></script>
<script src="data.js"></script>
<script src="sheet.js"></script>
<script src="layout.js"></script>
<script src="app.js"></script>
</body>
</html>
`;
}

for (const f of fs.readdirSync(root)) if (/^product-\d+\.html$/.test(f)) fs.unlinkSync(path.join(root, f));

for (const p of PRODUCTS) {
  const cat = catById[p.category];
  const title = `${p.title} — ${cedi(p.price)}`;
  const description = `${cedi(p.price)} · ${p.location} · ${p.seller}. Contact the seller directly on WhatsApp through Yɛntɔn Online.`;
  const file = `product-${p.id}.html`;
  write(file, productPage({
    head: `<title>${escape(p.title)} — Yɛntɔn Online</title>
  <meta name="description" content="${escape(description)}">
  ${previewTags({ title, description, url: base + file, image: previewImage(p.image), type: "product" })}`,
    product: p.id,
    crumbs: `<a href="index.html">Home</a> › <a href="shop.html">Shop</a> › <a href="shop.html?cat=${p.category}">${escape(cat.name)}</a>`,
    view: `<h1>${escape(p.title)}</h1>
      <p class="price big">${cedi(p.price)}</p>
      <p class="meta">📍 ${escape(p.location)} · ${escape(p.seller)}</p>`,
    moreTitle: `More in ${escape(cat.name)}`,
    moreLink: `shop.html?cat=${p.category}`,
  }));
}

// GitHub Pages shows 404.html for any missing address. For product-<id>.html it shows that product,
// so products added to the sheet work straight away, before the next build makes their own page.
const sitePath = new URL(base).pathname;
write("404.html", productPage({
  head: `<base href="${sitePath}">
  <title>Yɛntɔn Online</title>
  <meta name="robots" content="noindex">
  <script>document.documentElement.dataset.product = (location.pathname.match(/product-(\\d+)\\.html$/) || [])[1] || "";</script>`,
  crumbs: `<a href="index.html">Home</a> › <a href="shop.html">Shop</a>`,
  view: `<p class="empty">Loading…</p>`,
  moreTitle: "Featured products",
  moreLink: "shop.html",
}).replace('<body data-page="shop" data-product="">',
  '<body data-page="shop">\n<script>document.body.dataset.product = document.documentElement.dataset.product;</script>'));

// ---------- sitemap + robots ----------
const urls = [
  ...pages.filter((f) => f !== "report.html").map((f) => base + (f === "index.html" ? "" : f)),
  ...PRODUCTS.map((p) => base + `product-${p.id}.html`),
];
write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u}</loc></url>`).join("\n")}
</urlset>
`);
write("robots.txt", `User-agent: *\nAllow: /\nSitemap: ${base}sitemap.xml\n`);

console.log(`Updated ${pages.length} pages, wrote ${PRODUCTS.length} product pages, 404.html and sitemap.xml.`);
